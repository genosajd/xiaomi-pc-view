@Composable
fun strings(): Strings =
    if (LocalConfiguration.current.locales[0].language == "pl") PL else EN

/** the texts outside Compose (the widget) */
fun stringsFor(ctx: Context): Strings =
    if (ctx.resources.configuration.locales[0].language == "pl") PL else EN
